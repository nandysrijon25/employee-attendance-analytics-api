@app.on_event("startup")
def create_indexes():
    # Employee identity and department queries
    db.employees.create_index(
        [("emp_code", ASCENDING)],
        unique=True,
        name="uniq_employee_code",
    )
    db.employees.create_index(
        [("department", ASCENDING), ("emp_code", ASCENDING)],
        name="department_employee_code",
    )
    db.employees.create_index(
        [("department", ASCENDING), ("joined_on", ASCENDING)],
        name="department_joined_on",
    )

    # One attendance record per employee per attendance date
    db.attendance_logs.create_index(
        [("emp_code", ASCENDING), ("date", ASCENDING)],
        unique=True,
        name="uniq_employee_attendance_date",
    )

    # Attendance listing, employee history and date-range queries
    db.attendance_logs.create_index(
        [("date", DESCENDING), ("emp_code", ASCENDING)],
        name="attendance_date_employee",
    )
    db.attendance_logs.create_index(
        [("emp_code", ASCENDING), ("date", DESCENDING)],
        name="attendance_employee_date",
    )

    # Monthly late-record queries
    db.attendance_logs.create_index(
        [("date", ASCENDING), ("late_minutes", DESCENDING)],
        name="attendance_date_late",
    )



